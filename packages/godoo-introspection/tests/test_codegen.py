def test_generate_get_type_hints_round_trip(tmp_path: Path) -> None:
    """Verify generated code survives get_type_hints extraction.

    Uses importlib to load the generated .py file so that class annotations
    are resolved in a proper module context (avoids Python 3.14 exec/ForwardRef
    module-binding issue when the calling module uses from __future__ import annotations).
    """
    gen = CodeGenerator(None)  # type: ignore[arg-type]
    schema = _schema("res.partner", name=_char_field("name"))
    result = gen.generate(schema)
    # Write to a temp file and import it properly via importlib
    mod_file = tmp_path / "res_partner.py"
    mod_file.write_text(result, encoding="utf-8")
    spec = importlib.util.spec_from_file_location("res_partner_test", mod_file)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    cls = mod.ResPartner
    hints = typing.get_type_hints(cls, include_extras=True)
    assert "id" in hints
    # id should have Required origin
    assert typing.get_origin(hints["id"]) is typing.Required



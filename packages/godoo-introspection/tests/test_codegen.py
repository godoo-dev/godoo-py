def test_generate_empty_schema_pass() -> None:
    gen = CodeGenerator(None)  # type: ignore[arg-type]
    # Schema with no fields — body must contain 'pass' (id is always emitted, so
    # a schema with only id-equivalent coverage → use an empty fields dict)
    schema = ModelSchema(name="res.empty", fields={})
    result = gen.generate(schema)
    assert "pass" in result

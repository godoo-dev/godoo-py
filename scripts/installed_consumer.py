#!/usr/bin/env -S uv run --script
# /// script
# requires-python = "==3.14.8"
# dependencies = []
# ///
"""Executed with the isolated consumer interpreter, never with workspace imports."""

from __future__ import annotations

import asyncio
import hashlib
import importlib
import importlib.metadata as metadata
import json
import sys
import zipfile
from pathlib import Path


def main() -> None:
    manifest = json.loads(Path(sys.argv[1]).read_text())
    origins = {}
    for namespace in ("client", "introspection", "testcontainers"):
        module = importlib.import_module(f"godoo.{namespace}")
        location = Path(module.__file__).resolve()
        assert location.is_relative_to(Path(sys.prefix).resolve()), location
        assert (location.parent / "py.typed").is_file()
        origins[namespace] = str(location)
    for wheel in manifest["wheels"]:
        distribution = metadata.distribution(wheel["name"])
        assert distribution.version == wheel["version"]
        direct = json.loads(distribution.read_text("direct_url.json"))
        assert direct.get("dir_info", {}).get("editable") is not True
        archive = Path(sys.argv[1]).parent / wheel["filename"]
        assert hashlib.sha256(archive.read_bytes()).hexdigest() == wheel["sha256"]
        with zipfile.ZipFile(archive) as z:
            for name in z.namelist():
                if not name.endswith(("/", ".dist-info/RECORD")):
                    assert distribution.locate_file(name).read_bytes() == z.read(name), name
    meta = metadata.distribution("godoo")
    assert not meta.requires
    assert all(".dist-info/" in str(f) for f in meta.files)

    from godoo.client import OdooClient, OdooClientConfig
    from godoo.client.rpc.types import OdooSessionInfo
    from godoo.introspection import CodeGenerator, FieldSchema, Introspector, ModelSchema

    class Transport:
        """In-process protocol substitute; real JSON-RPC/Odoo is a separate proof."""

        def __init__(self):
            self.session = None
            self.calls = []

        async def authenticate(self, username, password):
            self.session = OdooSessionInfo(uid=7, session_id="disposable", db="fixture")
            return self.session

        async def call(self, model, method, args, kwargs):
            self.calls.append((model, method, args, kwargs))
            assert model == "res.partner" and method == "search_read"
            return [{"id": 42, "name": "Wheel consumer"}]

        def logout(self):
            self.session = None

        async def aclose(self):
            pass

    async def behavior():
        transport = Transport()
        client = OdooClient(
            OdooClientConfig(
                url="http://unused.invalid",
                database="fixture",
                username="disposable",
                password="disposable",
                transport_factory=lambda config: transport,
            )
        )
        try:
            await client.authenticate()
            records = await client.search_read("res.partner", [], fields=["name"], limit=1)
            assert records == [{"id": 42, "name": "Wheel consumer"}]
            output = Path.cwd() / "generated"
            output.mkdir()
            CodeGenerator(Introspector(client)).write(
                [ModelSchema(name="res.partner", fields={"name": FieldSchema(name="name", ttype="char")})], output
            )
            # Load generated bytes as an actual module and instantiate the generated public model.
            import importlib.util

            spec = importlib.util.spec_from_file_location("consumer_partner", output / "res_partner.py")
            module = importlib.util.module_from_spec(spec)
            sys.modules[spec.name] = module
            spec.loader.exec_module(module)
            partner = module.ResPartner(id=42, name=records[0]["name"])
            assert partner.name == "Wheel consumer" and partner.__odoo_model__ == "res.partner"
            assert transport.calls[0][3]["fields"] == ["name"]
        finally:
            await client.aclose()

    asyncio.run(behavior())
    print(
        json.dumps(
            {
                "origins": origins,
                "public_api": "client search_read + generated model round trip",
                "meta": "metadata-only; no dependencies",
                "live_odoo": False,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
